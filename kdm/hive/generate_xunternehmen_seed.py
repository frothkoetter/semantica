def sql_str(value: str | None) -> str:
    if value is None:
        return "NULL"
    return "'" + str(value).replace("'", "''") + "'"


def sql_bool(value: bool) -> str:
    return "TRUE" if value else "FALSE"


def sql_date(value: date) -> str:
    return f"DATE '{value.isoformat()}'"


def fmt_id(prefix: str, n: int) -> str:
    return f"{prefix}-{n:06d}"


class SqlWriter:
    def __init__(self, path: Path, batch_size: int = 500) -> None:
        self.path = path
        self.batch_size = batch_size
        self._fh = path.open("w", encoding="utf-8")
        self.stats: dict[str, int] = {}

    def close(self) -> None:
        self._fh.close()

    def write_header(self, counts: dict[str, int]) -> None:
        self._fh.write("-- XUnternehmen.Kerndatenmodell — large synthetic demo dataset\n")
        self._fh.write("-- Generated by kdm/hive/generate_xunternehmen_seed.py\n")
        self._fh.write("-- Run after kdm/hive/xunternehmen_ddl.sql\n\n")
        for key, val in counts.items():
            self._fh.write(f"-- {key}: {val:,} rows\n")
        self._fh.write("\n")

    def insert_batches(self, table: str, columns: Sequence[str], rows: Iterable[Sequence[Any]]) -> int:
        col_list = ", ".join(columns)
        batch: List[str] = []
        total = 0

        def flush() -> None:
            nonlocal total
            if not batch:
                return
            self._fh.write(f"INSERT INTO xunternehmen.{table} ({col_list}) VALUES\n")
            self._fh.write(",\n".join(batch))
            self._fh.write(";\n\n")
            total += len(batch)
            batch.clear()

        for row in rows:
            batch.append("  (" + ", ".join(str(v) for v in row) + ")")
            if len(batch) >= self.batch_size:
                flush()
        flush()
        self.stats[table] = self.stats.get(table, 0) + total
        return total


def rand_date(rng: random.Random, start_year: int = 1960, end_year: int = 2005) -> str:
    start = date(start_year, 1, 1)
    end = date(end_year, 12, 31)
    delta = (end - start).days
    return (start + timedelta(days=rng.randint(0, delta))).isoformat()


def rand_bwn(rng: random.Random) -> str:
    return "DE" + "".join(str(rng.randint(0, 9)) for _ in range(13))


def rand_idnr(rng: random.Random) -> str:
    return "".join(str(rng.randint(0, 9)) for _ in range(11))


def generate(args: argparse.Namespace) -> dict[str, int]:
    rng = random.Random(args.seed)
    counts = dict(ENTITY_COUNTS)
    if args.scale != 1.0:
        counts = {k: max(100, int(v * args.scale)) for k, v in counts.items()}

    n_np = counts["natuerliche_person"]
    n_jp = counts["juristische_person"]
    n_pg = counts["rechtsfaehige_personengesellschaft"]
    n_spv = counts["sonstige_personenvereinigung"]
    n_wt = counts["wirtschaftliche_taetigkeit"]
    n_as = counts["anschrift"]
    n_km = counts["kommunikation"]
    n_ei = counts["eintragung"]
    n_si = counts["sitz"]
    n_ev = counts["effektiver_verwaltungssitz"]
    n_bs = counts["betriebsstaette"]
    n_wz = counts["wirtschaftszweig"]
    n_an = counts["antrag"]
    n_az = counts["anzeige"]

    writer = SqlWriter(args.output, batch_size=args.batch_size)
    writer.write_header(counts)

    np_ids = [fmt_id("np", i) for i in range(1, n_np + 1)]
    jp_ids = [fmt_id("jp", i) for i in range(1, n_jp + 1)]
    pg_ids = [fmt_id("pg", i) for i in range(1, n_pg + 1)]
    spv_ids = [fmt_id("spv", i) for i in range(1, n_spv + 1)]
    wt_ids = [fmt_id("wt", i) for i in range(1, n_wt + 1)]

    # --- natuerliche_person ---
    def iter_np() -> Iterator[tuple]:
        for i, _np_id in enumerate(np_ids, start=1):
            geschlecht = rng.choice(GESCHLECHT)
            doktor = sql_str("Dr.") if rng.random() < 0.08 else "NULL"
            yield (
                sql_str(_np_id),
                doktor,
                sql_str(geschlecht),
                sql_str(rand_idnr(rng)),
                sql_str("000" if rng.random() < 0.92 else "124"),
            )

    writer.insert_batches(
        "natuerliche_person",
        ["id", "doktorgrad", "geschlecht_code", "identifikationsnummer", "staatsangehoerigkeit_code"],
        iter_np(),
    )

    # --- name_natuerliche_person (1:1) ---
    def iter_names() -> Iterator[tuple]:
        for i, _np_id in enumerate(np_ids, start=1):
            geschlecht = rng.choice(["m", "w"])
            vorname = rng.choice(VORNAMEN_M if geschlecht == "m" else VORNAMEN_W)
            nachname = rng.choice(NACHNAMEN)
            yield (
                sql_str(fmt_id("nn", i)),
                sql_str(_np_id),
                sql_str(vorname),
                sql_str(nachname),
                sql_str(nachname),
                sql_bool(False),
                sql_bool(False),
                sql_bool(False),
            )

    writer.insert_batches(
        "name_natuerliche_person",
        [
            "id", "natuerliche_person_id", "vornamen", "familienname", "geburtsname",
            "familienname_nicht_vorhanden", "geburtsname_nicht_vorhanden", "vornamen_nicht_vorhanden",
        ],
        iter_names(),
    )

    # --- geburt (1:1) ---
    def iter_geburt() -> Iterator[tuple]:
        for i, _np_id in enumerate(np_ids, start=1):
            stadt, _, _ = rng.choice(STAEDTE)
            yield (
                sql_str(fmt_id("gb", i)),
                sql_str(_np_id),
                sql_str(rand_date(rng)),
                sql_str(stadt),
                sql_str("000"),
            )

    writer.insert_batches(
        "geburt",
        ["id", "natuerliche_person_id", "geburtsdatum", "ort_der_geburt", "staat"],
        iter_geburt(),
    )

    # --- juristische_person ---
    def iter_jp() -> Iterator[tuple]:
        suffixes = ["GmbH", "AG", "SE", "gGmbH", "UG"]
        for i, _jp_id in enumerate(jp_ids, start=1):
            name = f"{rng.choice(NACHNAMEN)} {rng.choice(['Consulting', 'Service', 'Technik', 'Handel', 'Digital'])} {rng.choice(suffixes)}"
            yield (
                sql_str(_jp_id),
                sql_str(name),
                sql_str(rand_bwn(rng)),
                sql_str(rng.choice(RECHTSFORMEN)),
            )

    writer.insert_batches(
        "juristische_person",
        ["id", "eingetragener_name", "bundeseinheitliche_wirtschaftsnummer", "rechtsformen_code"],
        iter_jp(),
    )

    # --- rechtsfaehige_personengesellschaft ---
    def iter_pg() -> Iterator[tuple]:
        for i, _pg_id in enumerate(pg_ids, start=1):
            name = f"{rng.choice(NACHNAMEN)} & {rng.choice(NACHNAMEN)} OHG"
            yield (
                sql_str(_pg_id),
                sql_str(name),
                sql_str(rand_bwn(rng)),
                sql_str("221200"),
            )

    writer.insert_batches(
        "rechtsfaehige_personengesellschaft",
        ["id", "eingetragener_name", "bundeseinheitliche_wirtschaftsnummer", "rechtsformen_code"],
        iter_pg(),
    )

    # --- sonstige_personenvereinigung ---
    def iter_spv() -> Iterator[tuple]:
        for i, _spv_id in enumerate(spv_ids, start=1):
            name = f"Projekt {rng.choice(NACHNAMEN)} {rng.choice(['GbR', 'PartG', 'eG'])}"
            yield (
                sql_str(_spv_id),
                sql_str(name),
                sql_str(rand_bwn(rng)),
                sql_str("221300"),
            )

    writer.insert_batches(
        "sonstige_personenvereinigung",
        ["id", "eingetragener_name", "bundeseinheitliche_wirtschaftsnummer", "rechtsformen_code"],
        iter_spv(),
    )

    # --- wirtschaftliche_taetigkeit ---
    def iter_wt() -> Iterator[tuple]:
        for i, _wt_id in enumerate(wt_ids, start=1):
            base = rng.choice(NACHNAMEN)
            eingetragen = f"{base} {rng.choice(['IT', 'Beratung', 'Logistik', 'Handwerk', 'Gastro'])}"
            suffix = rng.choice(["", "e.K.", "GbR"])
            registered = f"{eingetragen} {suffix}".strip()
            yield (
                sql_str(_wt_id),
                sql_str(registered),
                sql_str(rand_bwn(rng)),
                sql_str(rng.choice(RECHTSFORMEN)),
                sql_str(eingetragen),
                sql_str(rng.choice(["Dienstleistung", "Handel", "Produktion", "Beratung", "Gastronomie"])),
            )

    writer.insert_batches(
        "wirtschaftliche_taetigkeit",
        [
            "id", "eingetragener_name", "bundeseinheitliche_wirtschaftsnummer", "rechtsformen_code",
            "geschaeftsbezeichnung", "taetigkeit",
        ],
        iter_wt(),
    )

    # --- anschrift ---
    anschrift_typen = ["INLAND_STRASSE", "INLAND_POSTFACH", "INLAND_GROSSEMPFAENGER", "AUSLAND"]
    as_ids = [fmt_id("as", i) for i in range(1, n_as + 1)]

    def iter_anschrift() -> Iterator[tuple]:
        for i, _as_id in enumerate(as_ids, start=1):
            typ = rng.choices(
                anschrift_typen,
                weights=[0.72, 0.12, 0.1, 0.06],
                k=1,
            )[0]
            stadt, plz, ags = rng.choice(STAEDTE)
            if typ == "AUSLAND":
                yield (
                    sql_str(_as_id), sql_str(typ), sql_str("04"),
                    sql_str(rng.choice(STRASSEN)), sql_str(str(rng.randint(1, 120))),
                    sql_str("1010"), sql_str("Wien"), sql_str("124"),
                    "NULL", "NULL", "NULL", "NULL", "NULL",
                )
            elif typ == "INLAND_POSTFACH":
                yield (
                    sql_str(_as_id), sql_str(typ), sql_str("02"),
                    "NULL", "NULL", sql_str(plz), sql_str(stadt), sql_str("000"),
                    sql_str(str(rng.randint(1000, 999999))), "NULL", "NULL", "NULL", "NULL",
                )
            elif typ == "INLAND_GROSSEMPFAENGER":
                yield (
                    sql_str(_as_id), sql_str(typ), sql_str("03"),
                    sql_str(rng.choice(STRASSEN)), sql_str(str(rng.randint(1, 50))),
                    sql_str(plz), sql_str(stadt), sql_str("000"),
                    sql_str(str(rng.randint(100000, 999999))), "NULL", "NULL", "NULL", "NULL",
                )
            else:
                yield (
                    sql_str(_as_id), sql_str(typ), sql_str("01"),
                    sql_str(rng.choice(STRASSEN)), sql_str(str(rng.randint(1, 200))),
                    sql_str(plz), sql_str(stadt), sql_str("000"),
                    "NULL", sql_str(ags), "NULL", "NULL", sql_str("Hinterhaus") if rng.random() < 0.05 else "NULL",
                )

    writer.insert_batches(
        "anschrift",
        [
            "id", "anschrift_typ", "art_anschrift_code", "strasse", "hausnummer", "postleitzahl", "ort", "staat",
            "postfach", "gemeindeschluessel_code", "frueherer_gemeindename", "wohnungsinhaber", "zusatzangaben_anschrift",
        ],
        iter_anschrift(),
    )

    # --- zuordnung_anschrift ---
    za_counter = 0

    def owners_for_anschrift() -> List[tuple[str, str]]:
        owners: List[tuple[str, str]] = []
        for _id in np_ids:
            owners.append(("NatuerlichePerson", _id))
        for _id in jp_ids:
            owners.append(("JuristischePerson", _id))
        for _id in pg_ids:
            owners.append(("RechtsfaehigePersonengesellschaft", _id))
        for _id in spv_ids:
            owners.append(("SonstigePersonenvereinigung", _id))
        for _id in wt_ids:
            owners.append(("WirtschaftlicheTaetigkeit", _id))
        rng.shuffle(owners)
        return owners

    owner_pool = owners_for_anschrift()
    # reuse / wrap owners until we have n_as links
    while len(owner_pool) < n_as:
        owner_pool.extend(owners_for_anschrift())
    owner_pool = owner_pool[:n_as]

    def iter_zuordnung_anschrift() -> Iterator[tuple]:
        nonlocal za_counter
        for i, (owner_typ, owner_id) in enumerate(owner_pool):
            za_counter += 1
            yield (
                sql_str(fmt_id("za", za_counter)),
                sql_str(owner_typ),
                sql_str(owner_id),
                sql_str(as_ids[i]),
            )

    writer.insert_batches(
        "zuordnung_anschrift",
        ["id", "owner_typ", "owner_id", "anschrift_id"],
        iter_zuordnung_anschrift(),
    )

    # --- kommunikation ---
    km_art = ["EMAIL", "TELEFON", "TELEFAX", "DEMAIL", "WEB"]
    km_ids = [fmt_id("km", i) for i in range(1, n_km + 1)]

    def iter_kommunikation() -> Iterator[tuple]:
        for i, _km_id in enumerate(km_ids, start=1):
            art = rng.choices(km_art, weights=[0.45, 0.3, 0.05, 0.05, 0.15], k=1)[0]
            base = f"demo{i}"
            email = telefon = telefax = demail = web = "NULL"
            if art == "EMAIL":
                email = sql_str(f"{base}@example-xunternehmen.de")
            elif art == "TELEFON":
                telefon = sql_str(f"+49 421 {rng.randint(1000000, 9999999)}")
            elif art == "TELEFAX":
                telefax = sql_str(f"+49 421 {rng.randint(1000000, 9999999)}")
            elif art == "DEMAIL":
                demail = sql_str(f"{base}@demo.de-mail.de")
            else:
                web = sql_str(f"https://www.example-xunternehmen-{i % 500}.de")
            yield (
                sql_str(_km_id),
                sql_str(art),
                sql_str(rng.choice(["01", "02", "03"])),
                sql_str("Geschaeftlich") if rng.random() < 0.7 else "NULL",
                email, telefon, telefax, demail, web,
            )

    writer.insert_batches(
        "kommunikation",
        [
            "id", "kommunikation_art", "klassifikation_kommunikation_code", "kommunikation_hinweis",
            "emailadresse", "telefonnummer", "telefaxnummer", "demailadresse", "webadresse",
        ],
        iter_kommunikation(),
    )

    owner_pool_km = owners_for_anschrift()
    while len(owner_pool_km) < n_km:
        owner_pool_km.extend(owners_for_anschrift())
    owner_pool_km = owner_pool_km[:n_km]
    zk_counter = 0

    def iter_zuordnung_kommunikation() -> Iterator[tuple]:
        nonlocal zk_counter
        for i, (owner_typ, owner_id) in enumerate(owner_pool_km):
            zk_counter += 1
            yield (
                sql_str(fmt_id("zk", zk_counter)),
                sql_str(owner_typ),
                sql_str(owner_id),
                sql_str(km_ids[i]),
            )

    writer.insert_batches(
        "zuordnung_kommunikation",
        ["id", "owner_typ", "owner_id", "kommunikation_id"],
        iter_zuordnung_kommunikation(),
    )

    # --- eintragung + zuordnung ---
    ei_ids = [fmt_id("ei", i) for i in range(1, n_ei + 1)]

    def iter_eintragung() -> Iterator[tuple]:
        for i, _ei_id in enumerate(ei_ids, start=1):
            stadt, _, _ = rng.choice(STAEDTE)
            yield (
                sql_str(_ei_id),
                sql_str(rng.choice(["01", "02", "03"])),
                sql_str(f"HRB {rng.randint(10000, 99999)}"),
                sql_str("K1101"),
                sql_str(f"Amtsgericht {stadt}"),
                sql_str(stadt),
                sql_str("000"),
                "NULL",
            )

    writer.insert_batches(
        "eintragung",
        [
            "id", "art_eintragung_code", "eintragungsnummer", "registergericht_code",
            "registergericht_bezeichnung", "ort", "staat", "stiftungsverzeichnis",
        ],
        iter_eintragung(),
    )

    ei_owners: List[tuple[str, str]] = []
    for _id in jp_ids:
        ei_owners.append(("JuristischePerson", _id))
    for _id in pg_ids:
        ei_owners.append(("RechtsfaehigePersonengesellschaft", _id))
    for _id in spv_ids:
        ei_owners.append(("SonstigePersonenvereinigung", _id))
    for _id in wt_ids:
        ei_owners.append(("WirtschaftlicheTaetigkeit", _id))
    rng.shuffle(ei_owners)
    while len(ei_owners) < n_ei:
        ei_owners.extend(ei_owners[:])
    ei_owners = ei_owners[:n_ei]
    ze_counter = 0

    def iter_zuordnung_eintragung() -> Iterator[tuple]:
        nonlocal ze_counter
        for i, (owner_typ, owner_id) in enumerate(ei_owners):
            ze_counter += 1
            yield (
                sql_str(fmt_id("ze", ze_counter)),
                sql_str(owner_typ),
                sql_str(owner_id),
                sql_str(ei_ids[i]),
            )

    writer.insert_batches(
        "zuordnung_eintragung",
        ["id", "owner_typ", "owner_id", "eintragung_id"],
        iter_zuordnung_eintragung(),
    )

    # --- sitz ---
    si_ids = [fmt_id("si", i) for i in range(1, n_si + 1)]

    def iter_sitz() -> Iterator[tuple]:
        for i, _si_id in enumerate(si_ids, start=1):
            stadt, _, _ = rng.choice(STAEDTE)
            yield (sql_str(_si_id), sql_str(stadt), sql_str("000"))

    writer.insert_batches("sitz", ["id", "ort", "staat"], iter_sitz())

    si_owners: List[tuple[str, str]] = []
    for _id in jp_ids:
        si_owners.append(("JuristischePerson", _id))
    for _id in pg_ids:
        si_owners.append(("RechtsfaehigePersonengesellschaft", _id))
    for _id in spv_ids:
        si_owners.append(("SonstigePersonenvereinigung", _id))
    rng.shuffle(si_owners)
    while len(si_owners) < n_si:
        si_owners.extend(si_owners[:])
    si_owners = si_owners[:n_si]
    zs_counter = 0

    def iter_zuordnung_sitz() -> Iterator[tuple]:
        nonlocal zs_counter
        for i, (owner_typ, owner_id) in enumerate(si_owners):
            zs_counter += 1
            yield (
                sql_str(fmt_id("zs", zs_counter)),
                sql_str(owner_typ),
                sql_str(owner_id),
                sql_str(si_ids[i]),
            )

    writer.insert_batches(
        "zuordnung_sitz",
        ["id", "owner_typ", "owner_id", "sitz_id"],
        iter_zuordnung_sitz(),
    )

    # --- effektiver_verwaltungssitz ---
    ev_ids = [fmt_id("ev", i) for i in range(1, n_ev + 1)]

    def iter_ev() -> Iterator[tuple]:
        for i, _ev_id in enumerate(ev_ids, start=1):
            stadt, _, _ = rng.choice(STAEDTE)
            yield (sql_str(_ev_id), sql_str(stadt), sql_str("000"))

    writer.insert_batches("effektiver_verwaltungssitz", ["id", "ort", "staat"], iter_ev())

    ev_owners: List[tuple[str, str]] = []
    for _id in jp_ids:
        ev_owners.append(("JuristischePerson", _id))
    for _id in pg_ids:
        ev_owners.append(("RechtsfaehigePersonengesellschaft", _id))
    rng.shuffle(ev_owners)
    while len(ev_owners) < n_ev:
        ev_owners.extend(ev_owners[:])
    ev_owners = ev_owners[:n_ev]
    zev_counter = 0

    def iter_zuordnung_ev() -> Iterator[tuple]:
        nonlocal zev_counter
        for i, (owner_typ, owner_id) in enumerate(ev_owners):
            zev_counter += 1
            yield (
                sql_str(fmt_id("zev", zev_counter)),
                sql_str(owner_typ),
                sql_str(owner_id),
                sql_str(ev_ids[i]),
            )

    writer.insert_batches(
        "zuordnung_effektiver_verwaltungssitz",
        ["id", "owner_typ", "owner_id", "effektiver_verwaltungssitz_id"],
        iter_zuordnung_ev(),
    )

    # --- betriebsstaette ---
    bs_ids = [fmt_id("bs", i) for i in range(1, n_bs + 1)]
    wt_for_bs = [rng.choice(wt_ids) for _ in range(n_bs)]

    def iter_bs() -> Iterator[tuple]:
        for i, _bs_id in enumerate(bs_ids, start=1):
            yield (
                sql_str(_bs_id),
                sql_str(wt_for_bs[i - 1]),
                sql_str(rng.choice(["01", "02", "03"])),
            )

    writer.insert_batches(
        "betriebsstaette",
        ["id", "wirtschaftliche_taetigkeit_id", "art_betriebsstaette_code"],
        iter_bs(),
    )

    # betriebsstaette anschrift links (subset)
    def iter_bs_anschrift() -> Iterator[tuple]:
        for i, _bs_id in enumerate(bs_ids[: min(n_bs, 2000)], start=1):
            yield (
                sql_str(fmt_id("za", za_counter + i)),
                sql_str("Betriebsstaette"),
                sql_str(_bs_id),
                sql_str(as_ids[(n_as - i) % n_as]),
            )

    extra_za = min(n_bs, 2000)
    za_counter += extra_za
    writer.insert_batches(
        "zuordnung_anschrift",
        ["id", "owner_typ", "owner_id", "anschrift_id"],
        iter_bs_anschrift(),
    )

    # --- wirtschaftszweig ---
    wz_ids = [fmt_id("wz", i) for i in range(1, n_wz + 1)]

    def iter_wz() -> Iterator[tuple]:
        for i, _wz_id in enumerate(wz_ids, start=1):
            yield (
                sql_str(_wz_id),
                sql_str(rng.choice(wt_ids)),
                sql_str(rng.choice(WZ_CODES)),
                sql_str("WZ2008"),
            )

    writer.insert_batches(
        "wirtschaftszweig",
        ["id", "wirtschaftliche_taetigkeit_id", "wirtschaftszweigschluessel", "version_wirtschaftszweigschluessel_code"],
        iter_wz(),
    )

    # --- antrag / anzeige ---
    an_ids = [fmt_id("an", i) for i in range(1, n_an + 1)]
    az_ids = [fmt_id("az", i) for i in range(1, n_az + 1)]

    def iter_antrag() -> Iterator[tuple]:
        base = date(2024, 1, 1)
        for i, _an_id in enumerate(an_ids, start=1):
            yield (
                sql_str(_an_id),
                sql_str(f"GWA-2026-{i:05d}"),
                sql_date(base + timedelta(days=rng.randint(0, 600))),
            )

    writer.insert_batches("antrag", ["id", "vorgangsnummer", "eingangsdatum"], iter_antrag())

    def iter_anzeige() -> Iterator[tuple]:
        base = date(2024, 1, 1)
        for i, _az_id in enumerate(az_ids, start=1):
            yield (
                sql_str(_az_id),
                sql_str(f"GWA-2026-A{i:05d}"),
                sql_date(base + timedelta(days=rng.randint(0, 600))),
            )

    writer.insert_batches("anzeige", ["id", "vorgangsnummer", "eingangsdatum"], iter_anzeige())

    # --- Rollen ---
    subject_types = [
        "NatuerlichePerson",
        "JuristischePerson",
        "RechtsfaehigePersonengesellschaft",
        "SonstigePersonenvereinigung",
        "WirtschaftlicheTaetigkeit",
    ]

    def pick_subject() -> tuple[str, str]:
        typ = rng.choice(subject_types)
        if typ == "NatuerlichePerson":
            return typ, rng.choice(np_ids)
        if typ == "JuristischePerson":
            return typ, rng.choice(jp_ids)
        if typ == "RechtsfaehigePersonengesellschaft":
            return typ, rng.choice(pg_ids)
        if typ == "SonstigePersonenvereinigung":
            return typ, rng.choice(spv_ids)
        return typ, rng.choice(wt_ids)

    def iter_rwt() -> Iterator[tuple]:
        for i, wt_id in enumerate(wt_ids, start=1):
            styp, sid = pick_subject()
            yield (sql_str(fmt_id("rwt", i)), sql_str(wt_id), sql_str(styp), sql_str(sid))

    writer.insert_batches(
        "rolle_wirtschaftlich_taetiger",
        ["id", "wirtschaftliche_taetigkeit_id", "subject_typ", "subject_id"],
        iter_rwt(),
    )

    def iter_rgs() -> Iterator[tuple]:
        for i in range(1, n_pg * 2 + 1):
            pg_id = pg_ids[(i - 1) % n_pg]
            styp = rng.choice(["NatuerlichePerson", "JuristischePerson", "RechtsfaehigePersonengesellschaft"])
            if styp == "NatuerlichePerson":
                sid = rng.choice(np_ids)
            elif styp == "JuristischePerson":
                sid = rng.choice(jp_ids)
            else:
                sid = rng.choice(pg_ids)
            yield (
                sql_str(fmt_id("rgs", i)),
                sql_str(pg_id),
                sql_str(styp),
                sql_str(sid),
                sql_str(rng.choice(["01", "02", "03"])),
            )

    writer.insert_batches(
        "rolle_gesellschafter",
        ["id", "personengesellschaft_id", "subject_typ", "subject_id", "art_gesellschafter_code"],
        iter_rgs(),
    )

    def iter_rgv() -> Iterator[tuple]:
        for i in range(1, n_jp + n_np // 2 + 1):
            rep_typ = rng.choice(["JuristischePerson", "NatuerlichePerson"])
            rep_id = rng.choice(jp_ids if rep_typ == "JuristischePerson" else np_ids)
            vert_typ = rng.choice(["NatuerlichePerson", "JuristischePerson"])
            vert_id = rng.choice(np_ids if vert_typ == "NatuerlichePerson" else jp_ids)
            yield (
                sql_str(fmt_id("rgv", i)),
                sql_str(rep_typ),
                sql_str(rep_id),
                sql_str(vert_typ),
                sql_str(vert_id),
                sql_str(rng.choice(["1", "2", "3", "4"])),
            )

    writer.insert_batches(
        "rolle_gesetzlicher_vertreter",
        [
            "id", "represented_typ", "represented_id", "vertreter_typ", "vertreter_id",
            "art_gesetzlicher_vertreter_code",
        ],
        iter_rgv(),
    )

    def iter_rbt() -> Iterator[tuple]:
        for i in range(1, n_spv * 2 + 1):
            yield (
                sql_str(fmt_id("rbt", i)),
                sql_str(spv_ids[(i - 1) % n_spv]),
                sql_str(rng.choice(np_ids)),
            )

    writer.insert_batches(
        "rolle_beteiligter",
        ["id", "sonstige_personenvereinigung_id", "natuerliche_person_id"],
        iter_rbt(),
    )

    def iter_rat() -> Iterator[tuple]:
        for i, an_id in enumerate(an_ids, start=1):
            styp, sid = pick_subject()
            yield (
                sql_str(fmt_id("rat", i)),
                sql_str(an_id),
                sql_str(styp),
                sql_str(sid),
                sql_str(rng.choice(["01", "02"])),
            )

    writer.insert_batches(
        "rolle_antragsteller",
        ["id", "antrag_id", "subject_typ", "subject_id", "art_angabe_antragsteller_anzeigender_code"],
        iter_rat(),
    )

    def iter_raz() -> Iterator[tuple]:
        for i, az_id in enumerate(az_ids, start=1):
            styp, sid = pick_subject()
            yield (
                sql_str(fmt_id("raz", i)),
                sql_str(az_id),
                sql_str(styp),
                sql_str(sid),
                sql_str(rng.choice(["01", "02"])),
            )

    writer.insert_batches(
        "rolle_anzeigender",
        ["id", "anzeige_id", "subject_typ", "subject_id", "art_angabe_antragsteller_anzeigender_code"],
        iter_raz(),
    )

    def iter_rhp() -> Iterator[tuple]:
        for i in range(1, n_an + n_az + 1):
            if i <= n_an:
                yield (sql_str(fmt_id("rhp", i)), sql_str("Antrag"), sql_str(an_ids[i - 1]), sql_str(rng.choice(np_ids)))
            else:
                j = i - n_an - 1
                yield (sql_str(fmt_id("rhp", i)), sql_str("Anzeige"), sql_str(az_ids[j]), sql_str(rng.choice(np_ids)))

    writer.insert_batches(
        "rolle_handelnde_person",
        ["id", "vorgang_typ", "vorgang_id", "natuerliche_person_id"],
        iter_rhp(),
    )

    def iter_rap() -> Iterator[tuple]:
        for i in range(1, n_an + n_az + 1):
            if i <= n_an:
                yield (sql_str(fmt_id("rap", i)), sql_str("Antrag"), sql_str(an_ids[i - 1]), sql_str(rng.choice(np_ids)))
            else:
                j = i - n_an - 1
                yield (sql_str(fmt_id("rap", i)), sql_str("Anzeige"), sql_str(az_ids[j]), sql_str(rng.choice(np_ids)))

    writer.insert_batches(
        "rolle_ansprechpartner",
        ["id", "vorgang_typ", "vorgang_id", "natuerliche_person_id"],
        iter_rap(),
    )

    writer.close()
    return writer.stats


def main() -> int:
    parser = argparse.ArgumentParser(description="Generate large XUnternehmen KDM seed SQL")
    parser.add_argument("--output", type=Path, default=DEFAULT_OUTPUT)
    parser.add_argument("--batch-size", type=int, default=500)
    parser.add_argument("--seed", type=int, default=42)
    parser.add_argument(
        "--scale",
        type=float,
        default=1.0,
        help="Scale all entity counts (e.g. 0.2 for a smaller file during dev)",
    )
    args = parser.parse_args()

    stats = generate(args)
    total = sum(stats.values())
    size_mb = args.output.stat().st_size / (1024 * 1024)
    print(f"Wrote {args.output} ({size_mb:.1f} MB, {total:,} INSERT rows across {len(stats)} tables)")
    for table, count in sorted(stats.items()):
        print(f"  {table}: {count:,}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
